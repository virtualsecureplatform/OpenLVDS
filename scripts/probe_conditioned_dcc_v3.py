"""Joint native conditioner, clock-release and buffered-TG DCC source pilot.

Reset is generated by actual conditioned-clock NAND storage, not a timed ideal
internal reset. Matching release-controller replicas load both clock phases.
No source pilot admits the physical clock backend or changes hardware warmup.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import fcntl
import hashlib
import itertools
import json
import os
from pathlib import Path
import subprocess
import native_clock_release_v3 as release
import probe_conditioned_dcc_v2 as failed_source
import probe_continuous_clock_conditioner_v2 as front
import probe_dcc_tg_ratio_v2 as sizing
from measure_conditioned_dcc_v2 import measure
from spice_dispatch import lease
from spice_engine import command,provenance
from probe_digital_dcc_v2 import sha,write,atomic

ROOT=front.ROOT
VERSION='joint-native-conditioned-dcc-and-direct-request-release-v2.2'


def fixture(out,spec,devices):
    period=1000/spec['mhz'];origin=spec['raw_start_ns'];a=spec['slew0_ps']/1000;b=spec['slew180_ps']/1000
    request=origin+3*period+a/2+.15
    model=Path(os.environ['PDK_ROOT'])/'sky130A/libs.tech/ngspice/sky130.lib.spice'
    probes={'R0','R180','F0','F180','P0','P180','MON0','MON180','Q','VDD','VDDIO','PB','NB','XF:VCM','REQUEST','RESET_N','RESET_180'}
    probes.update(n for d in devices for n in d['terminals'] if n!='0')
    pins=dict(VGND='0',VPWR='VDD',clock_out='Q',phase0='P0',phase180='P180',reset_n='RESET_N')
    return (f'OpenLVDS {VERSION}\n.lib "{model}" {spec["process"]}\n'
        f'.include "{out}/frontend.spice"\n.include "{out}/bias.spice"\n.include "{out}/clean.spice"\n'
        f'.include "{out}/release.spice"\n.include "{out}/{spec["variant"]}.spice"\n'
        f'.options device temp={spec["temperature"]}\n.options timeint method=gear reltol=1e-4 abstol=1e-12\n'
        'VDD VDD 0 1.8\nVDDIO VDDIO 0 3.3\nIREF PB 0 DC 35u\nXB PB NB VDDIO 0 lvds_bias\n'
        f'VR0 R0 0 PULSE(0 1.8 {origin}n {a:.15g}n {a:.15g}n {spec["duty"]*period-a:.15g}n {period:.15g}n)\n'
        f'VR180 R180 0 PULSE(0 1.8 {origin+period/2+(a-b)/2:.15g}n {b:.15g}n {b:.15g}n {spec["duty"]*period-b:.15g}n {period:.15g}n)\n'
        f'VREQUEST REQUEST 0 PWL(0 0 {request-.010:.15g}n 0 {request+.010:.15g}n 1.8)\n'
        f'XF R0 R180 F0 F180 PB VDDIO VDD 0 {front.frontend.PAIR}\n'
        f'XC F0 F180 P0 P180 MON0 MON180 VDD 0 {front.clean.NAME}\n'
        f'XR0 P0 REQUEST RESET_N VDD 0 {release.NAME}\nXR180 P180 REQUEST RESET_180 VDD 0 {release.NAME}\n'
        'XD '+' '.join(pins[p] for p in sizing.circuit.PORTS)+' '+sizing.circuit.NAME+'\n'
        f'CQ Q 0 {spec["load_ff"]}f\n.tran 1p {origin+22*period:.15g}n 0 1p\n'
        '.print tran '+' '.join('V('+n+')' for n in sorted(probes))+'\n.end\n')


def prepare(parent,ratios,failed):
    fm=front.bound(parent);rm=sizing.bound(ratios);pdk=Path(rm['identity']['pdk']);library=pdk.read_text()
    failed_source.bound(failed)
    for k in ['0','1']:
        row=json.loads((failed/k/'summary.json').read_text());result=row['result']
        if row['error'] is not None or not result['startup_passed'] or not result['half_cycle_passed'] or result['terminal_screen_passed']:
            raise ValueError('Require retained reset-controller-only stress failures')
        violations=[d for d in result['terminal_stress'] if not d['passed']]
        if not violations or any(not d['device'].startswith(('XR0:','XR180:')) for d in violations):
            raise ValueError('Failed pilot has a different stress cause')
    variants={v:sizing.circuit.source(v,library)[0] for v in ['p3','p4']};controller=release.source(library)
    for v,text in variants.items():
        if text!=(ratios/(v+'.spice')).read_text():raise ValueError('Native TG sizing source regeneration changed')
    base=[d for d in fm['identity']['devices'] if not d['name'].startswith('XD:')];devices={}
    for v,text in variants.items():
        group=list(base)
        group += front.clean.mapped_mos(text,dict(VGND='0',VPWR='VDD',clock_out='Q',phase0='P0',phase180='P180',reset_n='RESET_N'),'XD')
        for instance,clock,reset in [('XR0','P0','RESET_N'),('XR180','P180','RESET_180')]:
            group += front.clean.mapped_mos(controller,dict(CLK=clock,REQUEST='REQUEST',RESET_N=reset,VPWR='VDD',VGND='0'),instance)
        devices[v]=group
    paths=[Path(__file__),Path(release.__file__),ROOT/'scripts/measure_conditioned_dcc_v2.py',Path(front.__file__),Path(front.clean.__file__),
        Path(sizing.__file__),Path(sizing.circuit.__file__),ROOT/'scripts/dcc_tg_buffered_v2.py',ROOT/'scripts/dcc_tg_combiner_v2.py',
        ROOT/'scripts/dcc_nand_latch_v2.py',ROOT/'scripts/dcc_nand_mid_shunt_v2.py',ROOT/'scripts/native_static_cells_v2.py',ROOT/'scripts/build_compound_drivers_v3.py',
        ROOT/'scripts/run_ngspice.py',ROOT/'scripts/spice_dispatch.py',ROOT/'scripts/spice_engine.py',ROOT/'scripts/probe_digital_dcc_v2.py',
        parent/'manifest.json',ratios/'manifest.json',ratios/'p3.spice',ratios/'p4.spice']
    paths += [parent/n for n in ['frontend.spice','bias.spice','clean.spice']]
    paths += [Path(failed_source.__file__),ROOT/'scripts/native_clock_release_v2.py',failed/'manifest.json',failed/'0/summary.json',failed/'1/summary.json']
    specs=[dict(variant=v,process=p,temperature=40,mhz=410,load_ff=20,slew0_ps=a,slew180_ps=b,duty=d,raw_start_ns=front.RAW_START_NS)
        for v,p,(a,b),d in itertools.product(variants,['ss','sf'],[(100,100),(20,250),(250,20)],[.3,.7])]
    identity=dict(version=VERSION,parent=str(parent.relative_to(ROOT)),ratios=str(ratios.relative_to(ROOT)),
        inputs={str(p.relative_to(ROOT)):sha(p) for p in paths},pdk_files=rm['identity']['pdk_files'],simulator=provenance(),specs=specs,devices=devices)
    out=ROOT/'build/diagnostics/conditioned_dcc_v2'/hashlib.sha256(json.dumps(identity,sort_keys=True).encode()).hexdigest()[:16]
    out.mkdir(parents=True,exist_ok=False)
    for n in ['frontend.spice','bias.spice','clean.spice']:write(out/n,(parent/n).read_text())
    write(out/'release.spice',controller)
    for v,text in variants.items():write(out/(v+'.spice'),text)
    tasks=[]
    for n,spec in enumerate(specs):
        folder=out/str(n);folder.mkdir();write(folder/'bench.cir',fixture(out,spec,devices[spec['variant']]))
        tasks.append(dict(id=str(n),spec=spec,deck_sha256=sha(folder/'bench.cir')))
    atomic(out/'manifest.json',dict(identity=identity,tasks=tasks,libraries={p.name:sha(p) for p in out.glob('*.spice')},qualified_phy=False));return out


def bound(out):
    m=json.loads((out/'manifest.json').read_text());i=m['identity']
    if (i['version']!=VERSION or out.name!=hashlib.sha256(json.dumps(i,sort_keys=True).encode()).hexdigest()[:16]
        or any(sha(ROOT/n)!=h for n,h in i['inputs'].items()) or any(sha(Path(n))!=h for n,h in i['pdk_files'].items())
        or provenance()!=i['simulator'] or any(sha(out/n)!=h for n,h in m['libraries'].items()) or len(m['tasks'])!=len(i['specs'])):
        raise ValueError('Joint conditioned DCC source context changed')
    for n,task in enumerate(m['tasks']):
        if task['id']!=str(n) or task['spec']!=i['specs'][n] or sha(out/str(n)/'bench.cir')!=task['deck_sha256']:
            raise ValueError('Joint conditioned DCC task/deck changed')
    return m


def run(out):
    m=bound(out)
    with (out/'.execution.lock').open('a+') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        if (out/'state.json').exists():raise ValueError('Retain prior joint conditioned DCC pilot')
        atomic(out/'state.json',dict(status='running',qualified_phy=False))
        def execute(task):
            folder=out/task['id'];result=error=None
            try:
                with lease(ROOT,priority=0,label='conditioned_dcc_v2_'+task['id']):
                    bound(out);process=subprocess.run(command(folder/'ngspice.log',folder/'bench.cir'),capture_output=True,text=True)
                write(folder/'console.log',process.stdout+process.stderr);process.check_returncode()
                result=measure(folder,task['spec'],m['identity']['devices'][task['spec']['variant']],
                    'Joint native conditioner, actual static reset release and buffered TG source DCC only; no physical, full-PVT or PHY admission')
            except Exception as exception:error=str(exception)
            row=dict(task=task,result=result,error=error,files={p.name:sha(p) for p in folder.iterdir() if p.is_file()});atomic(folder/'summary.json',row);return row
        with ThreadPoolExecutor(max_workers=2) as pool:rows=list(pool.map(execute,m['tasks']))
        bound(out);atomic(out/'summary.json',dict(rows=rows,qualified_phy=False));atomic(out/'state.json',dict(status='joint_source_pilot_complete',cases=len(rows),errors=sum(r['error'] is not None for r in rows),qualified_phy=False))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('action',choices=['prepare','run','bound']);p.add_argument('artifact',type=Path);p.add_argument('--ratios',type=Path);p.add_argument('--failed-release',type=Path)
    a=p.parse_args();out=a.artifact.resolve()
    if a.action=='prepare':
        if a.ratios is None or a.failed_release is None:p.error('Provide TG sizing and retained failed release contexts')
        print(prepare(out,a.ratios.resolve(),a.failed_release.resolve()),flush=True)
    elif a.action=='run':run(out)
    else:print(json.dumps(bound(out),indent=2))
