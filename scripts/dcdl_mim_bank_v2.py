"""Physical bank topology with the measured parallel core and real MIM macros.

Coarse and fine ports are thermometer controls supplied by the admitted external
legal-code ROM. Real input/control buffers replace ideal stimulus drivers. This
topology needs fresh whole-bank DRC/LVS/RC and native characterization.
"""
import mim_switch_2x3_v2 as fine_unit
import mim_base_4x4_v2 as base_unit

VERSION='buffered-thermometer-balanced-mim-bank-v2.1'
SC='sky130_fd_sc_hd__'


def name(coarse_count=16,fine_count=32):
    if coarse_count not in [16,32,64,128,256] or fine_count not in [16,32]:raise ValueError('Undeclared bank search dimensions')
    return f'openlvds_dcdl_mim_c{coarse_count}_f{fine_count}_v2'


def controls(coarse_count=16,fine_count=32):
    name(coarse_count,fine_count)
    return [f'C{i}' for i in range(coarse_count-1)]+[f'E{i}' for i in range(fine_count-1)]


def instances(coarse_count=16,fine_count=32):
    controls(coarse_count,fine_count);cells=[]
    def add(instance,model,**pins):cells.append(dict(name=instance,model=model,pins=pins))
    def pair(instance,model,**pins):
        for copy in [0,1]:add(instance+f'_{copy}',SC+model,**pins)
    add('tie',SC+'conb_1',HI='high',LO='low')
    pair('input_buffer','buf_4',A='IN',X='f0')
    for i in range(coarse_count-1):
        add(f'coarse_buffer{i}',SC+'buf_4',A=f'C{i}',X=f'coarse{i}')
        pair(f'forward{i}','nand2_4',A=f'f{i}',B=f'coarse{i}',Y=f'f{i+1}')
        pair(f'turn{i}','nand2b_4',A_N=f'coarse{i}',B=f'f{i}',Y=f't{i}')
        pair(f'pass{i}','nand2b_4',A_N=f'r{i+1}',B=f'coarse{i}',Y=f'p{i}')
        pair(f'merge{i}','nand2_8' if i==0 else 'nand2_4',A=f't{i}',B=f'p{i}',Y=f'r{i}')
    last=coarse_count-1
    pair(f'turn{last}','nand2b_4',A_N='low',B=f'f{last}',Y=f't{last}')
    pair(f'merge{last}','nand2_4',A=f't{last}',B='high',Y=f'r{last}')
    pair('output_buffer','buf_4',A='r0',X='OUT')
    for i in range(fine_count-1):
        add(f'fine_buffer{i}',SC+'buf_1',A=f'E{i}',X=f'fine{i}')
        add(f'fine_inverse{i}',SC+'inv_1',A=f'fine{i}',Y=f'fine_b{i}')
        add(f'fine_unit{i}',fine_unit.NAME,NODE='r0',EN=f'fine{i}',ENB=f'fine_b{i}',VDD='VPWR',VSS='VGND')
    add('shared_base',base_unit.NAME,NODE='r0',VSS='VGND')
    return cells


def verilog(coarse_count=16,fine_count=32):
    top=name(coarse_count,fine_count);inputs=['IN',*controls(coarse_count,fine_count)]
    cells=instances(coarse_count,fine_count)
    nets=sorted({n for c in cells for n in c['pins'].values()}-set(inputs)-{'OUT','VPWR','VGND'})
    text=('// SPDX-License-Identifier: GPL-3.0-only\n// Generated by scripts/dcdl_mim_bank_v2.py; native whole-bank qualification required.\n'
        '`default_nettype none\nmodule '+top+' (\n`ifdef USE_POWER_PINS\n    inout wire VPWR,VGND,\n`endif\n'
        '    input wire '+','.join(inputs)+',\n    output wire OUT\n);\n'
        '`ifndef USE_POWER_PINS\n    supply1 VPWR; supply0 VGND;\n`endif\n'
        '    wire '+','.join(nets)+';\n')
    for cell in cells:
        text+='    (* keep="true", dont_touch="true" *) '+cell['model']+' '+cell['name']+' ('+','.join('.'+p+'('+n+')' for p,n in cell['pins'].items())+');\n'
    return text+'endmodule\n`default_nettype wire\n'


def blackboxes():
    text='// SPDX-License-Identifier: GPL-3.0-only\n`default_nettype none\n'
    for model,inputs,outputs in [('conb_1',[],['HI','LO']),('buf_4',['A'],['X']),('buf_1',['A'],['X']),
        ('inv_1',['A'],['Y']),('nand2_4',['A','B'],['Y']),('nand2_8',['A','B'],['Y']),('nand2b_4',['A_N','B'],['Y'])]:
        ports=([('input wire '+','.join(inputs))] if inputs else [])+['output wire '+','.join(outputs)]
        text+='(* blackbox *) module '+SC+model+'('+','.join(ports)+');endmodule\n'
    text+='(* blackbox *) module '+fine_unit.NAME+'(input wire NODE,EN,ENB,inout wire VDD,VSS);endmodule\n'
    text+='(* blackbox *) module '+base_unit.NAME+'(input wire NODE,inout wire VSS);endmodule\n'
    return text+'`default_nettype wire\n'


def spice(cell_ports,coarse_count=16,fine_count=32):
    top=name(coarse_count,fine_count);ports=['IN','OUT',*controls(coarse_count,fine_count),'VDD','VSS']
    orders=dict(cell_ports)
    orders[fine_unit.NAME]=['NODE','EN','ENB','VDD','VSS'];orders[base_unit.NAME]=['NODE','VSS']
    pg=dict(VPWR='VDD',VPB='VDD',VGND='VSS',VNB='VSS')
    text='.subckt '+top+' '+' '.join(ports)+'\n'
    for cell in instances(coarse_count,fine_count):
        pins={**pg,**cell['pins']}
        nodes=[pins[p] for p in orders[cell['model']]]
        nodes=[pg.get(n,n) for n in nodes]
        text+='X'+cell['name']+' '+' '.join(nodes)+' '+cell['model']+'\n'
    return text+'.ends '+top+'\n'
